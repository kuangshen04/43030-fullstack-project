import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceUrl = process.env.OPENAPI_URL ?? "http://localhost:8080/v3/api-docs";
const snapshotPath = path.join(rootDir, "openapi", "openapi.json");
const typesPath = path.join(
  rootDir,
  "packages",
  "api-client",
  "src",
  "generated",
  "schema.ts",
);

async function main() {
  console.log(`Fetching OpenAPI schema from ${sourceUrl} ...`);

  let response;
  try {
    response = await fetch(sourceUrl);
  } catch (error) {
    throw new Error(
      `Could not reach the API. Start it with "pnpm dev:api", then run "pnpm openapi:sync" again.`,
      { cause: error },
    );
  }

  if (!response.ok) {
    throw new Error(
      `The API returned HTTP ${response.status}. Check that the backend and database are running.`,
    );
  }

  const schema = await response.json();
  const ast = await openapiTS(schema, { alphabetize: true });
  const typeSource = astToString(ast);

  await mkdir(path.dirname(snapshotPath), { recursive: true });
  await mkdir(path.dirname(typesPath), { recursive: true });
  await writeFile(snapshotPath, `${JSON.stringify(schema, null, 2)}\n`, "utf8");
  await writeFile(
    typesPath,
    `// This file is generated by "pnpm openapi:sync". Do not edit it manually.\n${typeSource}`,
    "utf8",
  );

  console.log(`Saved schema snapshot: ${path.relative(rootDir, snapshotPath)}`);
  console.log(`Generated TypeScript types: ${path.relative(rootDir, typesPath)}`);
}

main().catch((error) => {
  console.error(`\nOpenAPI sync failed: ${error.message}`);
  process.exitCode = 1;
});
